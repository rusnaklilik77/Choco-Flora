const DICT = { ru, ro }

export function makeAdminT(lang) {
  const dict = DICT[lang] || ru
  return (key, vars) => {
    let value = dict[key]
    if (value === undefined) value = ru[key]
    if (value === undefined) return key
    if (typeof value === 'string' && vars) {
      return value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`))
    }
    return value
  }
}

export const AdminLangContext = createContext({
  lang: DEFAULT_ADMIN_LANG,
  setLang: () => {},
  t: makeAdminT(DEFAULT_ADMIN_LANG),
})

export const useAdminT = () => useContext(AdminLangContext)
